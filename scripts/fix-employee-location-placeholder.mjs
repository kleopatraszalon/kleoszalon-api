import fs from 'node:fs';
const path='src/routes/employees.ts';
let s=fs.readFileSync(path,'utf8');
const before='filters.push(`e.location_id::text=${values.length}::text`)';
const after='filters.push(`e.location_id::text=$${values.length}::text`)';
if(!s.includes(before))throw new Error('Expected broken employee location placeholder not found');
s=s.replace(before,()=>after);
if(!s.includes(after))throw new Error('Correct employee location placeholder was not written');
fs.writeFileSync(path,s,'utf8');
console.log('Employee location SQL placeholder restored to PostgreSQL $N form.');
